/* ---------- helpers ---------- */

function iso(minutesAgo: number): string {
  return new Date(Date.now() - minutesAgo * 60_000).toISOString();
}
function dayIso(daysAgo: number): string {
  const d = new Date(Date.now() - daysAgo * 86_400_000);
  return d.toISOString().slice(0, 10);
}

let chSeq = 0;
function makeChapters(
  workId: string,
  count: number,
  opts: {
    startNumber?: number;
    readUpTo?: number; // chapters with number <= this are read
    progressInLast?: number; // lastPage of the "current" chapter
    latestMinutesAgo?: number;
    intervalHours?: number;
    sizeMb?: number;
    downloadedNumbers?: number[];
    titles?: Record<number, string>;
  } = {}
): Chapter[] {
  const {
    startNumber = 1,
    readUpTo = 0,
    latestMinutesAgo = 3 * 24 * 60,
    intervalHours = 24 * 3,
    sizeMb = 14,
    downloadedNumbers = [],
    titles = {},
  } = opts;
  const chapters: Chapter[] = [];
  for (let i = 0; i < count; i++) {
    const number = startNumber + i;
    const releaseMs = Date.now() - (latestMinutesAgo * 60_000 + (count - 1 - i) * intervalHours * 3_600_000);
    const isRead = number <= readUpTo;
    const dl = downloadedNumbers.includes(number)
      ? "DONE"
      : ("NONE" as const);
    chapters.push({
      id: `${workId}-c${number}`,
      number,
      title: titles[number] ?? `Chapter ${number}`,
      pages: 14 + ((number * 7) % 12),
      releaseDate: new Date(releaseMs).toISOString(),
      scanlator: "Oni Scans",
      isRead,
      lastPage: number === readUpTo + 1 && opts.progressInLast ? opts.progressInLast : undefined,
      download: dl,
      sizeMb: sizeMb + ((number * 13) % 9),
    });
    chSeq++;
  }
  return chapters.reverse(); // latest first
}

